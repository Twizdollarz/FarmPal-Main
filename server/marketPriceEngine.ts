// Calculate Market Price Benchmarks vs Farmer Realized Price
export function calculateMarketBenchmarks(
  sales: SaleRecord[]
): {
  benchmarks: MarketPriceBenchmark[];
  insights: MarketAdvisoryInsight[];
  sources: VerifiedMarketSource[];
  lastSync: string;
} {
  // Compute weighted average realized selling price per crop from sales
  const farmerPrices: Record<string, { totalRev: number; totalQty: number; unit: string }> = {};

  for (const s of sales) {
    const key = s.cropName.toLowerCase();
    if (!farmerPrices[key]) {
      farmerPrices[key] = { totalRev: 0, totalQty: 0, unit: s.unit };
    }
    farmerPrices[key].totalRev += s.totalRevenue;
    farmerPrices[key].totalQty += s.quantitySold;
  }

  const benchmarks: MarketPriceBenchmark[] = activeBenchmarks.map((bench) => {
    const key = bench.cropName.toLowerCase();
    const farmerData = farmerPrices[key];
    const farmerRealizedAvgPrice =
      farmerData && farmerData.totalQty > 0 ? Math.round(farmerData.totalRev / farmerData.totalQty) : undefined;

    let priceGapVsFarmer: number | undefined = undefined;
    let priceGapPercent: number | undefined = undefined;
    let status: 'premium' | 'fair' | 'underpriced' | 'no_sales' = 'no_sales';

    if (farmerRealizedAvgPrice !== undefined) {
      priceGapVsFarmer = farmerRealizedAvgPrice - bench.wholesaleAvg;
      priceGapPercent = Math.round((priceGapVsFarmer / bench.wholesaleAvg) * 100);

      if (priceGapPercent >= 5) status = 'premium';
      else if (priceGapPercent >= -5) status = 'fair';
      else status = 'underpriced';
    }

    return {
      ...bench,
      farmerRealizedAvgPrice,
      priceGapVsFarmer,
      priceGapPercent,
      status,
    };
  });

  return {
    benchmarks,
    insights: defaultMarketInsights,
    sources: VERIFIED_MARKET_SOURCES,
    lastSync: lastSyncTimestamp,
  };
}

// Synchronize and update weekly prices
export function syncWeeklyMarketBenchmarks(
  sales: SaleRecord[]
): {
  benchmarks: MarketPriceBenchmark[];
  insights: MarketAdvisoryInsight[];
  sources: VerifiedMarketSource[];
  lastSync: string;
} {
  lastSyncTimestamp = new Date().toISOString();
  
  // Recalculate benchmarks to ensure current prices and 7-day shifts are fresh
  activeBenchmarks = defaultMarketBenchmarks.map((bench) => {
    const weekly = bench.weeklyPrices || [];
    const currentW = weekly[weekly.length - 1];
    const priorW = weekly.length >= 2 ? weekly[weekly.length - 2] : null;

    let changePercent7d = bench.changePercent7d;
    if (currentW && priorW && priorW.wholesaleAvg > 0) {
      changePercent7d = Math.round(((currentW.wholesaleAvg - priorW.wholesaleAvg) / priorW.wholesaleAvg) * 1000) / 10;
    }

    return {
      ...bench,
      changePercent7d,
      lastUpdated: `Week 4 Survey (Synchronized Just Now, ${new Date().toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit' })})`,
    };
  });

  return calculateMarketBenchmarks(sales);
}
